// Package events содержит события, которые SSP публикует во внешние
// системы (Kafka), и инфраструктуру вокруг них.
//
// Реализован паттерн outbox:
//
//  1. Бизнес-операция (Impression) в одной транзакции с БД
//     записывает событие в таблицу ssp.event_outbox.
//  2. Отдельный Worker читает неопубликованные записи и отправляет
//     их в Kafka через Publisher.
//  3. После успешной публикации запись помечается published_at.
//
// Гарантия: событие не потеряется, даже если Kafka недоступна
// в момент Impression. Оно подождёт в outbox и уйдёт позже.
// Семантика — at-least-once: одно событие может быть опубликовано
// повторно при сбое между Publish и MarkPublished. Consumer должен
// быть идемпотентным (ключ — auction_id).
